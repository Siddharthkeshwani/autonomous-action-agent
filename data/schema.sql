-- Leave room for the fixed IDs in seed_data.py.
CREATE TABLE IF NOT EXISTS public.customers (
    customer_id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    name text NOT NULL,
    email text NOT NULL UNIQUE,
    tier text NOT NULL,
    region text NOT NULL
);

CREATE TABLE IF NOT EXISTS public.subscriptions_orders (
    order_id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 2501) PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES public.customers,
    domain_type text NOT NULL CHECK (domain_type IN (
        'audio_sub', 'ecommerce', 'bfsi_card', 'healthcare_appt'
    )),
    item_name text NOT NULL,
    amount_inr numeric(12, 2) NOT NULL CHECK (amount_inr >= 0),
    status text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.transactions_upi (
    txn_id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 3001) PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES public.subscriptions_orders,
    bank_name text NOT NULL,
    payment_method text NOT NULL,
    status text NOT NULL CHECK (status IN ('SUCCESS', 'FAILED', 'PENDING')),
    failure_reason text,
    amount_inr numeric(12, 2) NOT NULL CHECK (amount_inr >= 0),
    txn_timestamp timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.support_tickets (
    ticket_id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 601) PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES public.customers,
    order_id bigint NOT NULL REFERENCES public.subscriptions_orders,
    category text NOT NULL,
    priority text NOT NULL,
    status text NOT NULL DEFAULT 'OPEN',
    created_at timestamptz NOT NULL DEFAULT now(),
    resolved_at timestamptz
);

CREATE TABLE IF NOT EXISTS public.audit_logs (
    log_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor text NOT NULL,
    action_type text NOT NULL,
    payload_json jsonb NOT NULL,
    approved_by text,
    created_at timestamptz NOT NULL DEFAULT now()
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'agent_readonly') THEN
        CREATE ROLE agent_readonly LOGIN NOINHERIT
            NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
    END IF;
END
$$;

REVOKE CREATE ON SCHEMA public FROM agent_readonly;
GRANT USAGE ON SCHEMA public TO agent_readonly;

-- Clear table privileges before granting the four allowed reads. DROP requires ownership.
REVOKE ALL ON public.customers, public.subscriptions_orders, public.transactions_upi,
    public.support_tickets, public.audit_logs FROM PUBLIC, agent_readonly;
GRANT SELECT ON public.customers, public.subscriptions_orders, public.transactions_upi,
    public.support_tickets TO agent_readonly;

ALTER TABLE public.audit_logs ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE
    table_name text;
BEGIN
    FOREACH table_name IN ARRAY ARRAY[
        'customers', 'subscriptions_orders', 'transactions_upi', 'support_tickets'
    ] LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
        EXECUTE format('DROP POLICY IF EXISTS agent_read ON public.%I', table_name);
        EXECUTE format(
            'CREATE POLICY agent_read ON public.%I FOR SELECT TO agent_readonly USING (true)',
            table_name
        );
    END LOOP;
END
$$;
